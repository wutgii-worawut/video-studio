// node compose-sync.mjs <project>
// Converts editable composition.json into a browser script usable from file:// and HTTP.
import { readFile, writeFile, rename, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { projectName } from './lib/production.mjs';
import { validateComposition } from './lib/composition.mjs';
const project=projectName(process.argv[2]);
const jsonPath=join('projects',project,'source','composition.json');
const scriptPath=join('projects',project,'source','composition-data.js');
const data=JSON.parse(await readFile(jsonPath,'utf8'));
if(data.id!==project)throw new Error('Composition ID must equal project folder');
validateComposition(data);
const temp=scriptPath+'.stage-'+process.pid;
try{
  await writeFile(temp,'// Generated by compose-sync.mjs from composition.json\nwindow.VIDEO_COMPOSITION = '+JSON.stringify(data)+';\n');
  await rename(temp,scriptPath);
}finally{await rm(temp,{force:true})}
console.log('Synced '+jsonPath+' to '+scriptPath);
