const GROUPS=[...new Set(LOCATIONS.map(l=>l.group))];
const DOC_EXT=['.md','.txt','.csv','.srt','.vtt','.json','.pdf','.docx','.xlsx','.pptx'];
const isDoc=(name:string)=>DOC_EXT.some(e=>name.toLowerCase().endsWith(e));
const DESTINATIONS=[{value:'assets',label:'Source images'},{value:'brand',label:'Brand media'},{value:'brand-sfx',label:'Brand sound effects'},{value:'documents',label:'Project documents'},{value:'brand-docs',label:'Brand documents'}];
const LOCATION_LABEL:Record<string,string>=Object.fromEntries(DESTINATIONS.map(d=>[d.value,d.label]));
// Where /api/studio/files/action may change this file; null = read-only (shared, generated, brand.md, other source media).
function managed(file:FileEntry):{location:string;folder:string}|null{
 if(file.metadataOnly)return null;
 const folder=file.folder||'';
 if(['image','audio','video'].includes(file.type)){
  if(file.root==='Brand media')return isSfx(file)?{location:'brand-sfx',folder:folder==='sfx'?'':folder.slice(4)}:{location:'brand',folder};
  if(file.root==='Source assets'&&(folder==='img'||folder.startsWith('img/')))return {location:'assets',folder:folder==='img'?'':folder.slice(4)};
 }
 if((file.type==='text'||file.type==='document')&&file.name.toLowerCase()!=='brand.md'){
  if(file.root==='Project Docs')return {location:'documents',folder};
  if(file.root==='Brand notes')return {location:'brand-docs',folder};
 }
 return null;
}
const ext=(name:string)=>(name.split('.').at(-1)||'').toUpperCase();

// Some codecs (e.g. HEIC on some systems) can't be decoded here; say so and keep the download link below.
function DetailImage({src,name}:{src:string;name:string}){
 const [failed,setFailed]=useState(false);
 return failed?<div className="readonly-box" role="status">Image preview unavailable — this codec isn’t supported here. Use “Open / download original”.</div>:<img src={src} alt={name} onError={()=>setFailed(true)}/>;
}
// Real waveform from the decoded file; only decoded once the card scrolls into view.
function Waveform({src,size,onDuration}:{src:string;size:number;onDuration?:(d:number)=>void}){
 const ref=useRef<HTMLDivElement>(null),[bars,setBars]=useState<number[]|null>(null);
 useEffect(()=>{
  const el=ref.current;if(!el||size>20*1024*1024)return;
  let dead=false;
  const observer=new IntersectionObserver(async([entry])=>{
   if(!entry.isIntersecting)return;observer.disconnect();
   try{
    const data=await (await fetch(src)).arrayBuffer();
    const audio=await new OfflineAudioContext(1,1,44100).decodeAudioData(data);
    const pcm=audio.getChannelData(0),step=Math.max(1,Math.floor(pcm.length/48)),peaks=[];
    for(let i=0;i<48;i++){let max=0;for(let j=i*step;j<Math.min(pcm.length,(i+1)*step);j+=8)max=Math.max(max,Math.abs(pcm[j]));peaks.push(max);}
    const top=Math.max(...peaks)||1;
    if(!dead){setBars(peaks.map(p=>Math.max(.04,p/top)));onDuration?.(audio.duration);}
   }catch{/* undecodable: keep the plain tile */}
  });
  observer.observe(el);return ()=>{dead=true;observer.disconnect()};
 },[src,size]);
 return <div className="waveform" ref={ref}>{bars?bars.map((b,i)=><span key={i} style={{height:b*100+'%'}}/>):<span className="wave-placeholder">♪</span>}</div>;
}
function MarkdownDetail({project,group,file,onOpenDoc}:{project:string;group:string;file:FileEntry;onOpenDoc:(target:string,hash?:string)=>void}){
 const [text,setText]=useState<string|null>(null),[error,setError]=useState('');
 useEffect(()=>{let dead=false;setText(null);setError('');
  studioApi.text(project,group,file).then(r=>{if(!dead)setText(r.text)}).catch(e=>{if(!dead)setError((e as Error).message)});
  return ()=>{dead=true};},[project,group,file.path]);
 if(error)return <div className="readonly-box" role="status">{error}</div>;
 return text===null?<div className="skeleton" style={{height:120}}/>:<Suspense fallback={<div className="skeleton" style={{height:120}}/>}>
  <MarkdownView compact content={text} from={workspacePath(project,file)} project={project} onOpenDoc={onOpenDoc}/></Suspense>;
}
function Thumb({file,src,onBadge}:{file:FileEntry;src:string|null;onBadge:(v:string)=>void}){
 const [failed,setFailed]=useState(false);
 if(!src||failed||!file.previewable)return <div className="thumb-ext">{ext(file.name)}</div>;
 if(file.type==='image')return <img src={src} alt="" loading="lazy" onLoad={e=>onBadge(e.currentTarget.naturalWidth+'×'+e.currentTarget.naturalHeight)} onError={()=>setFailed(true)}/>;
 if(file.type==='audio')return <Waveform src={src} size={file.size} onDuration={d=>onBadge(d<10?d.toFixed(1)+'s':formatTime(d).slice(0,5))}/>;
 if(file.type==='video')return <><video src={src+'#t=0.1'} preload="metadata" muted playsInline onLoadedMetadata={e=>onBadge(formatTime(e.currentTarget.duration).slice(0,5))} onError={()=>setFailed(true)}/><span className="thumb-play"><Play size={16} fill="currentColor"/></span></>;
 return <div className="thumb-ext">{ext(file.name)}</div>;
}
function Card({file,src,selected,onClick}:{file:FileEntry;src:string|null;selected:boolean;onClick:()=>void}){
 const [badge,setBadge]=useState('');
 return <button className={cn('media-card',selected&&'selected')} onClick={onClick} title={[file.folder,file.name].filter(Boolean).join('/')}>
  <div className={cn('media-thumb',file.type)}><Thumb file={file} src={src} onBadge={setBadge}/>{badge&&<span className="thumb-badge">{badge}</span>}</div>
  <span className="media-name">{file.name}</span>
 </button>;
}

export function LibraryPage(){
 const {project,location,set,openFile,go,setMdMode}=useStudio(useShallow(s=>({project:s.project,location:s.libraryLocation,set:s.set,openFile:s.openFile,go:s.go,setMdMode:s.setMdMode})));
 const [lists,setLists]=useState<Record<string,FileEntry[]>>({}),[trash,setTrash]=useState<DeletedEntry[]>([]);
 const [query,setQuery]=useState(''),[selectedPath,setSelectedPath]=useState(''),[loading,setLoading]=useState(false),[busy,setBusy]=useState(false);
 const [importOpen,setImportOpen]=useState(false),[uploadTo,setUploadTo]=useState('assets'),[staged,setStaged]=useState<File[]>([]);
 const [renameTo,setRenameTo]=useState(''),[deleting,setDeleting]=useState<FileEntry|null>(null);
 const picker=useRef<HTMLInputElement>(null);
 const loc=LOCATIONS.find(l=>l.id===location);
 const reload=useCallback(async()=>{
  if(!project)return;setLoading(true);
  try{
   const [groups,deleted]=await Promise.all([Promise.all(GROUPS.map(g=>studioApi.entries(project,g).then(r=>r.entries))),studioApi.trash(project).then(r=>r.items)]);
   if(useStudio.getState().project!==project)return;
   setLists(Object.fromEntries(GROUPS.map((g,i)=>[g,groups[i]])));setTrash(deleted);
  }catch(e){toast.error((e as Error).message)}finally{setLoading(false)}
 },[project]);
 useEffect(()=>{void reload();},[reload]);
 const itemsOf=(l:Location)=>(lists[l.group]||[]).filter(l.keep);
 const items=useMemo(()=>loc?itemsOf(loc).filter(f=>!query||(f.folder+'/'+f.name).toLowerCase().includes(query.toLowerCase())):[],[loc,lists,query]);
 const selected=items.find(f=>f.path===selectedPath)||null;
 useEffect(()=>{set({libraryFile:selected})},[selected,set]);
 useEffect(()=>{setRenameTo(selected?.name||'')},[selected?.path]);
 const srcOf=(f:FileEntry)=>loc&&['image','audio','video'].includes(f.type)?urlFor('media',project,loc.group,f):loc&&f.type==='document'?urlFor('document',project,loc.group,f):null;
 const choose=(id:string)=>{set({libraryLocation:id});setSelectedPath('');setQuery('');};
 const act=async(type:'rename'|'duplicate'|'delete',file:FileEntry)=>{
  const where=managed(file);if(!where)return;
  setBusy(true);
  try{
   await studioApi.json('/api/studio/files/action',{action:type,project,...where,name:file.name,...(type==='rename'?{newName:renameTo.trim()}:{})});
   toast.success(type==='delete'?'Moved to Trash':type==='duplicate'?'Duplicated '+file.name:'Renamed to '+renameTo.trim());
   if(type!=='duplicate')setSelectedPath('');
   setDeleting(null);await reload();
  }catch(e){toast.error((e as Error).message)}finally{setBusy(false)}
 };
 const upload=async(files:File[],to:string)=>{
  setBusy(true);let imported=0;
  for(const file of files){
   if(isDoc(file.name)!==['documents','brand-docs'].includes(to)){toast.error(file.name+': choose a matching media/documents destination');continue;}
   try{await studioApi.upload(project,to,file);imported++}catch(e){toast.error(file.name+': '+(e as Error).message)}
  }
  setBusy(false);
  if(imported){toast.success(imported+' file(s) imported');setImportOpen(false);setStaged([]);await reload();}
 };
 // Drop anywhere: import straight into the open location when every file fits it, otherwise ask where.
 const onDrop=(e:React.DragEvent)=>{
  const files=Array.from(e.dataTransfer.files);if(!files.length)return;e.preventDefault();
  const to=loc?.importTo,fits=to&&files.every(f=>isDoc(f.name)===(to==='documents'));
  if(fits)void upload(files,to);else{setStaged(files);setUploadTo(to||'assets');setImportOpen(true);}
 };
 const restore=async(item:DeletedEntry)=>{
  setBusy(true);
  try{await studioApi.json('/api/studio/files/restore',{project,id:item.id});toast.success('Restored '+item.name);await reload();}
  catch(e){toast.error((e as Error).message)}finally{setBusy(false)}
 };
 const openInCode=(group:string,file:FileEntry)=>{if(isMarkdown(file))setMdMode('preview');void openFile(group,file);go('code');};
 const openDoc=(target:string,hash?:string)=>{const hit=findEntry({documents:lists.documents||[],fx:lists.fx||[]},project,target);
  if(!hit){toast.error('Not in the Library: '+target);return;}
  if(hash)set({mdAnchor:{key:hit.group+'|'+hit.file.path,id:hash}});
  openInCode(hit.group,hit.file);};
 const sections=[...new Set(LOCATIONS.map(l=>l.section))];
 const where=selected&&managed(selected);
 return <div className="library-page" onDragOver={e=>e.preventDefault()} onDrop={onDrop}>
  <nav className="library-locations" aria-label="Locations">
   {sections.map(section=><section key={section}><div className="tree-head">{section}</div>
    {LOCATIONS.filter(l=>l.section===section).map(l=><button key={l.id} className={cn('location-row',location===l.id&&'active')} aria-current={location===l.id?'true':undefined} onClick={()=>choose(l.id)}>
     <span>{l.label}</span><span className="count">{lists[l.group]?itemsOf(l).length:'–'}</span></button>)}</section>)}
   <section><button className={cn('location-row',location==='trash'&&'active')} aria-current={location==='trash'?'true':undefined} onClick={()=>choose('trash')}><span>Trash</span><span className="count">{trash.length}</span></button></section>
  </nav>
  <section className="library-main" aria-label={loc?.label||'Trash'}>
   <div className="library-head"><h1>{loc?.label||'Trash'}</h1>
    {loc&&<div className="projects-search"><Search size={15}/><Input value={query} onChange={e=>setQuery(e.target.value)} placeholder="Search…" aria-label="Search files"/></div>}
    <Button size="icon" variant="ghost" aria-label="Refresh files" onClick={()=>void reload()}><RefreshCw size={15} className={loading?'spin':''}/></Button>
    {loc?.importTo&&<Button size="sm" onClick={()=>{setStaged([]);setUploadTo(loc.importTo!);setImportOpen(true)}}><Plus size={14}/> Import</Button>}
   </div>
   <p className="library-note">{loc?(loc.importTo?<>Drop files anywhere on this page to import into <strong>{loc.label}</strong>. Same name? It’s kept as a copy — nothing is overwritten. 100 MB per file.</>:loc.readOnly):
    'Restore puts the file back where it came from and never overwrites a file with the same name.'}</p>
   {loc?<div className="media-grid" data-testid="file-list">{items.map(f=><Card key={f.path} file={f} src={srcOf(f)} selected={f.path===selectedPath} onClick={()=>setSelectedPath(f.path)}/>)}
     {!items.length&&<div className="empty-state"><p>{lists[loc.group]?'No files here yet':'Loading…'}</p></div>}</div>:
    <div className="trash-list">{trash.map(item=><div key={item.id} className="trash-row">
     <div><strong>{item.name}</strong><small>from {LOCATION_LABEL[item.location]||item.location} · {formatSize(item.size)} · deleted {new Date(item.deletedAt).toLocaleString()}</small></div>
     <Button size="sm" variant="secondary" disabled={busy} aria-label={'Restore '+item.name} onClick={()=>void restore(item)}><ArchiveRestore size={14}/> Restore</Button></div>)}
     {!trash.length&&<div className="empty-state"><p>Trash is empty</p><small>Files you move to Trash appear here for recovery.</small></div>}</div>}
  </section>
  <aside className="library-detail" aria-label="File details">{selected&&loc?<>
   {isMarkdown(selected)?<div className="detail-markdown"><MarkdownDetail key={selected.path} project={project} group={loc.group} file={selected} onOpenDoc={openDoc}/></div>:
   <div className={cn('detail-preview',selected.type)}>{(()=>{const src=srcOf(selected);
    if(!src||!selected.previewable)return <div className="thumb-ext">{ext(selected.name)}</div>;
    if(selected.type==='image')return <DetailImage key={src} src={src} name={selected.name}/>;
    if(selected.type==='video')return <video src={src} controls preload="metadata" aria-label={'Video preview '+selected.name}/>;
    if(selected.type==='audio')return <><Waveform src={src} size={selected.size}/><audio src={src} controls preload="metadata" aria-label={'Audio preview '+selected.name}/></>;
    if(selected.name.toLowerCase().endsWith('.pdf'))return <iframe title={selected.name} src={src}/>;
    return <div className="thumb-ext">{ext(selected.name)}</div>;})()}</div>}
   <strong className="detail-name">{selected.name}</strong>
   <span className="side-note">{selected.folder?selected.root+' / '+selected.folder:selected.root} · {formatSize(selected.size)}</span>
   {(()=>{const src=srcOf(selected);return src&&<a className="side-link" href={selected.type==='image'?src+'&download=1':src} download={selected.name}>Open / download original</a>})()}
   {selected.type==='text'&&<Button size="sm" variant="outline" onClick={()=>openInCode(loc.group,selected)}>Open in Code</Button>}
   {where?<div className="detail-actions">
    <label className="form-label" htmlFor="library-name">Name</label>
    <div className="inline-form"><Input id="library-name" value={renameTo} onChange={e=>setRenameTo(e.target.value)} onKeyDown={e=>{if(e.key==='Enter'&&renameTo.trim()&&renameTo!==selected.name)void act('rename',selected)}}/>
     <Button size="sm" variant="secondary" disabled={busy||!renameTo.trim()||renameTo===selected.name} onClick={()=>void act('rename',selected)}>Rename</Button></div>
    <Button size="sm" variant="secondary" disabled={busy} onClick={()=>void act('duplicate',selected)}>Duplicate</Button>
    <Button size="sm" variant="outline" className="danger-outline" disabled={busy} onClick={()=>setDeleting(selected)}><Trash2 size={14}/> Move to Trash</Button>
    <p className="side-note">Scenes that use this file may stop rendering until it’s restored.</p>
   </div>:<p className="readonly-box">{loc.readOnly||(selected.name.toLowerCase()==='brand.md'?'brand.md is the project brief — edit its text in Code, but it can’t be renamed or deleted.':'Read-only here. Ask Claude in the Terminal to change it.')}</p>}
  </>:<div className="empty-state"><p>Select a file</p><small>Preview, rename, duplicate or move it to Trash.</small></div>}</aside>

  <Dialog open={importOpen} onOpenChange={setImportOpen}><DialogContent>
   <div className="dialog-eyebrow"><Upload size={17}/> IMPORT</div>
   <DialogTitle className="dialog-title">Add files to project</DialogTitle>
   <DialogDescription>Pick where they go. Existing files are never overwritten.</DialogDescription>
   <label className="form-label" htmlFor="destination">Destination</label>
   <select id="destination" className="ui-input" value={uploadTo} onChange={e=>setUploadTo(e.target.value)}>{DESTINATIONS.map(d=><option key={d.value} value={d.value}>{d.label}</option>)}</select>
   <div className="drop-area" role="button" tabIndex={0} onKeyDown={e=>{if(e.key==='Enter')picker.current?.click()}} onClick={()=>picker.current?.click()} onDragOver={e=>e.preventDefault()} onDrop={e=>{e.preventDefault();e.stopPropagation();setStaged(Array.from(e.dataTransfer.files));}}>
    <Upload size={26}/><strong>Drop files here</strong><small>or click to choose files • 100 MB maximum per file</small>
   </div>
   <input ref={picker} type="file" multiple className="visually-hidden" onChange={e=>setStaged(Array.from(e.target.files||[]))} aria-label="Choose files to import"/>
   {staged.length>0&&<div className="file-staging">{staged.map((f,i)=><span key={i}><Check size={13}/>{f.name} <small>{formatSize(f.size)}</small></span>)}</div>}
   <DialogFooter><Button variant="outline" onClick={()=>setImportOpen(false)}>Cancel</Button><Button disabled={busy||!staged.length} onClick={()=>void upload(staged,uploadTo)}>{busy?'Importing…':'Import '+staged.length+' file(s)'}</Button></DialogFooter>
  </DialogContent></Dialog>
  <AlertDialog open={deleting!==null} onOpenChange={o=>{if(!o)setDeleting(null)}}><AlertDialogContent><div className="dialog-icon-danger"><Trash2 size={23}/></div>
   <AlertDialogTitle className="dialog-title">Move file to Trash?</AlertDialogTitle>
   <AlertDialogDescription>You are about to remove <strong>{deleting?.name}</strong> from this project. Scenes referencing this file may stop rendering correctly. You can restore it later from Trash.</AlertDialogDescription>
   <DialogFooter><AlertDialogCancel asChild><Button variant="outline" disabled={busy}>Cancel</Button></AlertDialogCancel><AlertDialogAction asChild><Button variant="destructive" disabled={busy} onClick={e=>{e.preventDefault();if(deleting)void act('delete',deleting)}}><Trash2 size={15}/> Move to Trash</Button></AlertDialogAction></DialogFooter>
  </AlertDialogContent></AlertDialog>
 </div>;
}
